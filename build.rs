//! Embed the shipped skills and mapping files in the library.
//!
//! An `ath` executable copied into an empty directory must still install the
//! agent skill and read its shipped mappings. This script lists every file
//! under `skills/` and `mappings/` and writes a table of `include_bytes!`
//! entries into `OUT_DIR`. The compiler then stores the bytes in the binary.
//!
//! Hidden names, such as `.DS_Store`, are skipped. A symbolic link stops the
//! build, because the embedded set must be the files that are actually in the
//! repository.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));

    let mut generated = String::from("// Generated by build.rs from skills/ and mappings/. Do not edit.\n\n");
    for (constant, directory) in [("SKILL_FILES", "skills"), ("MAPPING_FILES", "mappings")] {
        let root = asset_root(&manifest, directory);
        println!("cargo:rerun-if-changed={}", root.display());
        let mut files = Vec::new();
        collect(&root, &root, &mut files);
        files.sort();
        writeln!(generated, "pub(crate) static {constant}: &[EmbeddedFile] = &[").unwrap();
        for relative in &files {
            let absolute = root.join(relative);
            println!("cargo:rerun-if-changed={}", absolute.display());
            let absolute = absolute.to_str().expect("asset paths are UTF-8");
            writeln!(generated, "    EmbeddedFile {{ path: {relative:?}, bytes: include_bytes!({absolute:?}) }},")
                .unwrap();
        }
        writeln!(generated, "];\n").unwrap();
    }
    fs::write(out_dir.join("embedded_assets.rs"), generated).expect("write embedded asset table");

    // The release-archive update instructions name the archive for this target.
    let target = env::var("TARGET").expect("TARGET");
    println!("cargo:rustc-env=ATH_BUILD_TARGET={target}");
    println!("cargo:rerun-if-changed=build.rs");
}

/// `skills/` and `mappings/` sit beside `Cargo.toml`.
fn asset_root(manifest: &Path, name: &str) -> PathBuf {
    let candidate = manifest.join(name);
    if !candidate.is_dir() {
        panic!("the shipped {name}/ directory was not found beside {}", manifest.display());
    }
    fs::canonicalize(&candidate).expect("canonical asset directory")
}

/// Every regular file under `directory`, as a `/`-separated path relative to `root`.
fn collect(root: &Path, directory: &Path, out: &mut Vec<String>) {
    let mut entries: Vec<_> = fs::read_dir(directory)
        .unwrap_or_else(|error| panic!("read {}: {error}", directory.display()))
        .map(|entry| entry.expect("directory entry"))
        .collect();
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let name = entry.file_name();
        let name = name.to_str().unwrap_or_else(|| panic!("asset name is not UTF-8 in {}", directory.display()));
        if name.starts_with('.') {
            continue;
        }
        let path = entry.path();
        let file_type = fs::symlink_metadata(&path).expect("asset metadata").file_type();
        if file_type.is_symlink() {
            panic!("refusing to embed a symbolic link: {}", path.display());
        }
        if file_type.is_dir() {
            collect(root, &path, out);
        } else if file_type.is_file() {
            let relative = path.strip_prefix(root).expect("asset under its root");
            let parts: Vec<&str> =
                relative.components().map(|component| component.as_os_str().to_str().expect("UTF-8")).collect();
            out.push(parts.join("/"));
        }
    }
}
